const a=require('node:assert/strict');
const team=require('../team10-state.js');
const roster=team.roster;
a.equal(roster.length,10);
a.deepEqual(roster.reduce((v,p)=>(v[p.team]=(v[p.team]||0)+1,v),{}),{'0':1,'1':2,'2':3,'3':2,'4':2});
a.equal(new Set(roster.map(p=>p.id)).size,10);
a.equal(new Set(roster.map(p=>p.coordinates.join(','))).size,10);
a.equal(roster.find(p=>p.id===3).name,'임민채대리');
